export function textWidth(s) {
  return s.length * 4 - 1;
}

export function drawText(ctx, s, x, y, c, k = 1) {
  ctx.fillStyle = c;
  let cx = Math.round(x);
  const yy = Math.round(y);
  for (const ch of String(s)) {
    const g = G[ch] || G[ch.toUpperCase()];
    if (g) for (let i = 0; i < 15; i++) if (g[i] === "1") ctx.fillRect(cx + (i % 3) * k, yy + ((i / 3) | 0) * k, k, k);
    cx += 4 * k;
  }
}

export function drawTextCentered(ctx, s, cx, y, c, k = 1) {
  drawText(ctx, s, cx - (textWidth(s) * k) / 2, y, c, k);
}
